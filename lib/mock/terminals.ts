export function terminalsForVendor(vendorId: string): MockTerminal[] {
  return mockTerminals.filter((t) => t.vendorId === vendorId);
}

export function terminalsForOwner(ownerId: string): MockTerminal[] {
  return mockTerminals.filter((t) => t.ownerId === ownerId);
}

export function terminalById(id: string): MockTerminal | undefined {
  return mockTerminals.find((t) => t.id === id);
}

/** Live telemetry only exists above the `listed` tier. */
export function isConnected(tier: MockTerminal['connectivityTier']): boolean {
  return tier === 'connected_live' || tier === 'connected_demo';
}
